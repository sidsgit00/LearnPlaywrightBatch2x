// types of operators in JavaScript

// 1) Arithmetic Operators
let a = 10;
let b = 3;
console.log('Addition:', a + b); // 13
console.log('Subtraction:', a - b); // 7
console.log('Multiplication:', a * b);
console.log('Division:', a / b); // 3.3333
console.log('Modulus:', a % b); // 1
console.log('Exponentiation:', a ** b); // 1000         

// comparison operators // returns boolean values T/F
console.log('loose comparison Equal to:', a == b); // false
console.log('Not equal to:', a != b); // true
console.log('Strict equal to:', a === b); // false
console.log('Strict not equal to:', a !== b); // true
console.log('Greater than:', a > b); // true
console.log('Less than:', a < b); // false
console.log('Greater than or equal to:', a >= b); // true // a>b or a==b 
console.log('Less than or equal to:', a <= b); // false 



